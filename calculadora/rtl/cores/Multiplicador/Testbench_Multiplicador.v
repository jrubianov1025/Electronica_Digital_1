`timescale 1ns/1ps

module tb_Periferico_multiplicador;

//--------------------------------------------------
// REGISTROS Y WIRES
//--------------------------------------------------

reg clk;
reg reset;

reg [15:0] d_in;
reg cs;
reg [4:0] addr;
reg rd;
reg wr;

wire [31:0] d_out;

//--------------------------------------------------
// INSTANCIA DEL PERIFERICO
//--------------------------------------------------

Periferico_multiplicador DUT (

    .clk(clk),
    .reset(reset),
    .d_in(d_in),
    .cs(cs),
    .addr(addr),
    .rd(rd),
    .wr(wr),
    .d_out(d_out)

);

//--------------------------------------------------
// GENERACION DE CLOCK
//--------------------------------------------------

always #5 clk = ~clk; // periodo = 10ns

//--------------------------------------------------
// TASKS
//--------------------------------------------------

task WRITE;

    input [4:0] direccion;
    input [15:0] dato;

    begin

        @(posedge clk);

        cs   <= 1'b1;
        wr   <= 1'b1;
        rd   <= 1'b0;

        addr <= direccion;
        d_in <= dato;

        @(posedge clk);

        cs   <= 1'b0;
        wr   <= 1'b0;
        addr <= 5'd0;
        d_in <= 16'd0;

    end

endtask


task READ;

    input [4:0] direccion;

    begin

        @(posedge clk);

        cs   <= 1'b1;
        rd   <= 1'b1;
        wr   <= 1'b0;

        addr <= direccion;

        @(posedge clk);

        $display("READ addr = %h --> d_out = %d", direccion, d_out);

        cs   <= 1'b0;
        rd   <= 1'b0;
        addr <= 5'd0;

    end

endtask

//--------------------------------------------------
// SIMULACION
//--------------------------------------------------

initial begin

    //--------------------------------------------------
    // GENERAR VCD PARA GTKWAVE
    //--------------------------------------------------

    $dumpfile("tb_Periferico_multiplicador.vcd");
    $dumpvars(0, tb_Periferico_multiplicador);

    //--------------------------------------------------
    // INICIALIZACION
    //--------------------------------------------------

    clk   = 0;
    reset = 1;

    cs    = 0;
    rd    = 0;
    wr    = 0;

    addr  = 0;
    d_in  = 0;

    //--------------------------------------------------
    // RESET
    //--------------------------------------------------

    #20;
    reset = 0;

    //--------------------------------------------------
    // ESCRIBIR MULTIPLICANDO = 7
    //--------------------------------------------------

    //WRITE(5'h04, 16'd7);
    WRITE(5'h04, -16'sd7);
    //--------------------------------------------------
    // ESCRIBIR MULTIPLICADOR = 3
    //--------------------------------------------------

    WRITE(5'h08, 16'd3);

    //--------------------------------------------------
    // INICIAR MULTIPLICACION
    //--------------------------------------------------

    WRITE(5'h0C, 16'd1);

    //--------------------------------------------------
    // ESPERAR DONE
    //--------------------------------------------------

    wait(DUT.DONE == 1'b1);

    //--------------------------------------------------
    // LEER RESULTADO
    //--------------------------------------------------

    READ(5'h10);

    //--------------------------------------------------
    // LEER DONE
    //--------------------------------------------------

    READ(5'h14);

    //--------------------------------------------------
    // FINALIZAR
    //--------------------------------------------------

    #50;

    $finish;

end

endmodule